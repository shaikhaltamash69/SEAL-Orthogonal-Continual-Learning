"""
tools/print_env.py

Inspects the current Python environment and writes runtime dependency versions,
CUDA availability, GPU hardware, and current Git commit hash to results/ENVIRONMENT.md.
Also provides get_environment_info() for run log recording.

Usage:
  python tools/print_env.py
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path


def get_git_commit() -> str:
    try:
        res = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return res.stdout.strip()
    except Exception:
        return "unknown"


def get_environment_info() -> dict:
    env_info = {
        "python": sys.version.split()[0],
        "python_full": sys.version,
        "git_commit": get_git_commit(),
    }

    # PyTorch
    try:
        import torch
        env_info["torch"] = getattr(torch, "__version__", "unknown")
        env_info["cuda_available"] = torch.cuda.is_available()
        env_info["cuda_version"] = getattr(torch.version, "cuda", None)
        if torch.cuda.is_available() and torch.cuda.device_count() > 0:
            env_info["gpu_name"] = torch.cuda.get_device_name(0)
            env_info["gpu_count"] = torch.cuda.device_count()
        else:
            env_info["gpu_name"] = "None (CPU)"
            env_info["gpu_count"] = 0
    except ImportError:
        env_info["torch"] = "not installed"
        env_info["cuda_available"] = False
        env_info["cuda_version"] = None
        env_info["gpu_name"] = "None"
        env_info["gpu_count"] = 0

    # Key packages
    for pkg in ["transformers", "peft", "bitsandbytes", "accelerate"]:
        try:
            mod = __import__(pkg)
            env_info[pkg] = getattr(mod, "__version__", "installed")
        except ImportError:
            env_info[pkg] = "not installed"

    return env_info


def generate_environment_markdown(info: dict) -> str:
    md_lines = [
        "# Execution Environment",
        "",
        f"- **Date Generated**: auto-generated by `tools/print_env.py`",
        f"- **Git Commit**: `{info['git_commit']}`",
        f"- **Python**: `{info['python']}`",
        f"- **PyTorch**: `{info['torch']}`",
        f"- **Transformers**: `{info['transformers']}`",
        f"- **PEFT**: `{info['peft']}`",
        f"- **BitsAndBytes**: `{info['bitsandbytes']}`",
        f"- **Accelerate**: `{info['accelerate']}`",
        f"- **CUDA Available**: `{info['cuda_available']}`",
        f"- **CUDA Version**: `{info['cuda_version']}`",
        f"- **GPU Hardware**: `{info['gpu_name']}` (count: {info['gpu_count']})",
        "",
    ]
    return "\n".join(md_lines)


def main():
    info = get_environment_info()
    md = generate_environment_markdown(info)

    out_dir = Path("results")
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "ENVIRONMENT.md"

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(md)

    print("=" * 60)
    print("Environment Information:")
    for k, v in info.items():
        if k != "python_full":
            print(f"  {k:16s}: {v}")
    print("=" * 60)
    print(f"Written to {out_file}")


if __name__ == "__main__":
    main()
